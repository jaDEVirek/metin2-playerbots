    n    INT UNSIGNED NOT NULL PRIMARY KEY,
    name VARCHAR(24) NOT NULL,
    job  TINYINT NULL,
    sex  TINYINT NULL,
    UNIQUE KEY name (name),
    KEY bucket (job, sex, n)
) ENGINE=MEMORY DEFAULT CHARSET=latin1;

